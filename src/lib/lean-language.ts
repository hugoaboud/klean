// Lean 4 grammar for highlight.js.
//
// highlight.js ships no Lean grammar, so KLEAN registers its own. It covers
// what matters when reading Lean: doc/module/line comments, strings and chars,
// keywords, numerals, attributes and the unicode binders/operators.

import hljs from "highlight.js/lib/core";
import type { LanguageFn } from "highlight.js";

const KEYWORDS = [
  "def",
  "theorem",
  "lemma",
  "axiom",
  "constant",
  "instance",
  "structure",
  "class",
  "inductive",
  "abbrev",
  "opaque",
  "example",
  "namespace",
  "section",
  "end",
  "mutual",
  "variable",
  "universe",
  "universes",
  "import",
  "prelude",
  "open",
  "export",
  "attribute",
  "deriving",
  "initialize",
  "set_option",
  "where",
  "let",
  "in",
  "do",
  "by",
  "have",
  "show",
  "from",
  "fun",
  "match",
  "with",
  "if",
  "then",
  "else",
  "return",
  "at",
  "macro",
  "macro_rules",
  "syntax",
  "notation",
  "infix",
  "infixl",
  "infixr",
  "prefix",
  "postfix",
  "elab",
  "elab_rules",
  "private",
  "protected",
  "noncomputable",
  "partial",
  "unsafe",
  "local",
  "scoped",
  "deriving",
];

const LITERALS = ["true", "false"];

const BUILT_INS = [
  "Type",
  "Prop",
  "Sort",
  "Nat",
  "Int",
  "Float",
  "String",
  "Char",
  "Bool",
  "List",
  "Array",
  "Option",
  "Unit",
  "Empty",
  "Fin",
  "Subtype",
  "Coe",
  "Function",
  "Injective",
  "Injective2",
  "sorry",
  "admit",
];

const lean: LanguageFn = () => ({
  name: "Lean",
  aliases: ["lean4"],
  keywords: {
    keyword: KEYWORDS,
    literal: LITERALS,
    built_in: BUILT_INS,
  },
  contains: [
    // Documentation comments come first so they win over plain block comments.
    {
      className: "comment",
      begin: /\/--(?!\/)/,
      end: /-\//,
      contains: [{ className: "doctag", begin: /@[a-zA-Z][\w.]*/ }],
      relevance: 4,
    },
    {
      className: "comment",
      begin: /\/-!(?!\/)/,
      end: /-\//,
      relevance: 4,
    },
    hljs.COMMENT("/-", "-/"),
    hljs.COMMENT("--", "$"),
    {
      className: "string",
      begin: /"/,
      end: /"/,
      illegal: /\n/,
      contains: [{ begin: /\\[\s\S]/, relevance: 0 }],
    },
    {
      className: "string",
      begin: /'(\\.|[^'\\])'/,
      relevance: 0,
    },
    hljs.C_NUMBER_MODE,
    {
      className: "attribute",
      begin: /@\[/,
      end: /\]/,
      relevance: 0,
    },
    {
      className: "variable",
      begin: /[α-ωΑ-Ωℕℤℚℝℂ∀∃λΠΣ][\w']*/,
      relevance: 0,
    },
    {
      className: "operator",
      begin: /[=<>→←↔∧∨¬≠≤≥∧∨⊢⊣λ⟨⟩⇒⇔+-/*^|]+/,
      relevance: 0,
    },
  ],
});

export default lean;
